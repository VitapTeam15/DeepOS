import React from 'react';
import { Lightbulb, Check, X, ArrowRight, AlertTriangle, AlertCircle, Info, Sparkles } from 'lucide-react';
import { NavLink } from 'react-router-dom';

export default function RecommendationCard({ recommendations = [], onDismiss, onAccept }) {
  if (!recommendations || recommendations.length === 0) {
    return (
      <div className="card">
        <div className="card-header">
          <div className="card-title-group">
            <div className="card-title-icon">
              <Lightbulb size={16} />
            </div>
            <div>
              <h3>System Recommendations</h3>
              <p>Active suggestions for system and workflow optimization</p>
            </div>
          </div>
        </div>
        <div className="card-body">
          <div style={{ padding: '2rem 1rem', textAlign: 'center', color: 'var(--text-muted)' }}>
            <p style={{ fontSize: '0.88rem' }}>No pending system recommendations at this time.</p>
            <p style={{ fontSize: '0.78rem', color: 'var(--text-dim)', marginTop: '0.25rem' }}>
              Deep OS will suggest resource or workflow tuning as needed.
            </p>
          </div>
        </div>
      </div>
    );
  }

  const getSeverityIcon = (sev = '') => {
    const s = sev.toLowerCase();
    if (s === 'critical') return <AlertCircle size={18} />;
    if (s === 'warning') return <AlertTriangle size={18} />;
    return <Info size={18} />;
  };

  return (
    <div className="card">
      <div className="card-header">
        <div className="card-title-group">
          <div className="card-title-icon">
            <Lightbulb size={16} />
          </div>
          <div>
            <h3>Active Recommendations</h3>
            <p>Proactive actions generated by the intelligence engine</p>
          </div>
        </div>
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
          <span className="badge badge-primary">{recommendations.length} Pending</span>
          <NavLink to="/recommendations" className="btn btn-ghost btn-sm">
            View all
          </NavLink>
        </div>
      </div>

      <div className="card-body">
        <div style={{ display: 'flex', flexDirection: 'column', gap: '0.75rem' }}>
          {recommendations.slice(0, 3).map((rec) => {
            const sev = (rec.severity || 'info').toLowerCase();
            return (
              <div key={rec.id} className="recommendation-card-item">
                <div className={`rec-badge-icon ${sev}`}>
                  {getSeverityIcon(sev)}
                </div>

                <div className="rec-content-area">
                  <div className="rec-title-row">
                    <h4>{rec.message}</h4>
                    <span className={`badge badge-${sev === 'critical' ? 'danger' : sev === 'warning' ? 'warning' : 'info'} badge-sm`}>
                      {sev}
                    </span>
                  </div>
                  <p className="rec-reason-text">
                    {rec.reason || 'Detected based on current system resource and app activity patterns.'}
                  </p>
                </div>

                <div style={{ display: 'flex', alignItems: 'center', gap: '0.45rem', flexShrink: 0 }}>
                  <button 
                    onClick={() => onAccept(rec.id)} 
                    className="btn btn-primary btn-sm" 
                    title="Accept and apply recommendation"
                  >
                    <Check size={14} /> Apply
                  </button>
                  <button 
                    onClick={() => onDismiss(rec.id)} 
                    className="btn btn-secondary btn-sm" 
                    title="Dismiss"
                  >
                    <X size={14} />
                  </button>
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
}